#!/usr/bin/env python3
"""Turn a sliced Perfect First Layer Test into a Z-offset ladder.

Each of the five tiles gets its own Z offset, so one print shows which
squish is right. Offsets are relative (SET_GCODE_OFFSET Z_ADJUST), so they
stack on top of whatever per-head offset the printer applies, and the sum is
undone after the last tile.

Each change is inserted just before the "G1 Z<first layer>" move that drops
the nozzle onto a tile, so it takes effect on that move and never mid-line.

    ./make_zladder.py sliced.gcode            # default ladder below
    ./make_zladder.py sliced.gcode -o out.gcode --offsets C=0 BL=-0.02 BR=-0.04 FR=-0.06 FL=-0.08

Tiles: C = center, BL/BR = back left/right, FL/FR = front left/right
(back = high Y).
"""
import argparse
import re
import sys

DEFAULT = {"C": 0.0, "BL": -0.02, "BR": -0.04, "FR": -0.06, "FL": -0.08}
NAMES = {"C": "center", "BL": "back left", "BR": "back right", "FR": "front right", "FL": "front left"}


def parse_offsets(items):
    offsets = dict(DEFAULT)
    for item in items or []:
        key, val = item.split("=")
        offsets[key.upper()] = float(val)
    return offsets


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("gcode")
    ap.add_argument("-o", "--output")
    ap.add_argument("--offsets", nargs="*", metavar="TILE=MM")
    args = ap.parse_args()
    offsets = parse_offsets(args.offsets)
    out_path = args.output or re.sub(r"\.gcode$", "", args.gcode) + "_zladder.gcode"

    lines = open(args.gcode).read().split("\n")

    center = re.search(r"CENTER=([-\d.]+),([-\d.]+)", "\n".join(lines))
    if not center:
        sys.exit("no EXCLUDE_OBJECT_DEFINE CENTER found; enable 'Label objects' in Orca")
    cx, cy = float(center.group(1)), float(center.group(2))

    def tile(x, y):
        if abs(x - cx) < 30 and abs(y - cy) < 30:
            return "C"
        return ("B" if y > cy else "F") + ("L" if x < cx else "R")

    layer_start = next(i for i, l in enumerate(lines) if l.startswith(";LAYER_CHANGE"))
    if sum(l.startswith(";LAYER_CHANGE") for l in lines) != 1:
        sys.exit("expected a single-layer print")

    # Find each tile's first extrusion, then the Z-drop line just before it.
    x = y = None
    inserts = []  # (line index of Z drop, tile)
    current = None
    for i in range(layer_start, len(lines)):
        code = lines[i].split(";")[0]
        if not code.startswith(("G0", "G1", "G2", "G3")):
            continue
        mx, my, me = (re.search(p, code) for p in (r"X([-\d.]+)", r"Y([-\d.]+)", r"E([-\d.]+)"))
        if mx:
            x = float(mx.group(1))
        if my:
            y = float(my.group(1))
        if me and float(me.group(1)) > 0 and x is not None:
            t = tile(x, y)
            if t != current:
                drop = next(j for j in range(i, layer_start, -1)
                            if re.match(r"G1 Z[\d.]+\s*$", lines[j].split(";")[0].strip() + " "))
                inserts.append((drop, t))
                current = t

    seen = [t for _, t in inserts]
    if sorted(seen) != sorted(DEFAULT):
        sys.exit(f"expected each tile printed once, got order {seen}")

    applied = 0.0
    patch = {}
    for drop, t in inserts:
        delta = round(offsets[t] - applied, 4)
        applied = offsets[t]
        patch[drop] = [
            f"RESPOND MSG=\"Z ladder: {NAMES[t]} tile at {offsets[t]:+.3f} mm\"",
            f"SET_GCODE_OFFSET Z_ADJUST={delta:.4f} MOVE=0",
        ]

    end = next(i for i, l in enumerate(lines) if l.startswith("EXCLUDE_OBJECT_END"))
    patch[end + 1] = [f"SET_GCODE_OFFSET Z_ADJUST={-applied:.4f} MOVE=0  ; undo Z ladder"]

    header = ["; Z ladder generated by make_zladder.py from " + args.gcode.split("/")[-1]]
    header += [f";   {NAMES[t]:<12} {offsets[t]:+.3f} mm" for _, t in inserts]

    # Keep Orca's header block first; the touchscreen and Moonraker read it.
    header_end = next((i for i, l in enumerate(lines) if l.startswith("; HEADER_BLOCK_END")), -1)
    patch.setdefault(header_end + 1, [])[:0] = header

    out = []
    for i, line in enumerate(lines):
        out.extend(patch.get(i, []))
        out.append(line)
    open(out_path, "w").write("\n".join(out))

    print(out_path)
    print("print order:", " -> ".join(f"{NAMES[t]} ({offsets[t]:+.2f})" for _, t in inserts))


if __name__ == "__main__":
    main()
